-- Restore the public service catalogue and add per-city service availability.
-- Safe to re-run: categories are matched by name and city availability has a unique key.

ALTER TABLE public.service_categories
  ADD COLUMN IF NOT EXISTS active boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS public.service_city_availability (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_category_id bigint NOT NULL REFERENCES public.service_categories(id) ON DELETE CASCADE,
  city text NOT NULL,
  is_available boolean NOT NULL DEFAULT true,
  notes text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS service_city_availability_category_city_key
  ON public.service_city_availability (service_category_id, lower(city));

ALTER TABLE public.service_city_availability ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_read_available_city_services" ON public.service_city_availability;
CREATE POLICY "public_read_available_city_services"
  ON public.service_city_availability FOR SELECT TO anon, authenticated
  USING (is_available = true);

