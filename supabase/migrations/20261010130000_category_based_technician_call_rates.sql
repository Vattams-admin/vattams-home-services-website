-- Technician-paid call rates vary by the exact appliance job, not only broad category.
-- Customer-facing service prices/platform fees remain separate.
ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS service_type text;

ALTER TABLE public.technician_jobs
  ADD COLUMN IF NOT EXISTS service_type text;

CREATE TABLE IF NOT EXISTS public.technician_call_rates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_category text NOT NULL,
  service_type text NOT NULL,
  call_rate_fee numeric(10,2) NOT NULL CHECK (call_rate_fee >= 0),
  is_active boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT technician_call_rates_category_type_key UNIQUE (service_category, service_type)
);

ALTER TABLE public.technician_call_rates ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS technician_call_rates_public_read ON public.technician_call_rates;
CREATE POLICY technician_call_rates_public_read
  ON public.technician_call_rates FOR SELECT TO anon, authenticated USING (is_active = true);

