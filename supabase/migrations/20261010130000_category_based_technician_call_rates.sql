-- Keep the broad category-level fee sensible for older admin views.
-- New bookings use technician_call_rates and snapshot the exact job-specific fee.
UPDATE public.service_prices
SET call_rate_fee = CASE
  WHEN service_name IN ('AC Repair', 'AC Service') THEN 150
  WHEN service_name IN ('Washing Machine', 'Washing Machine Repair',
                        'Refrigerator', 'Refrigerator Repair') THEN 200
  ELSE call_rate_fee
END,
updated_at = now()
WHERE service_name IN (
  'AC Repair', 'AC Service',
  'Washing Machine', 'Washing Machine Repair',
  'Refrigerator', 'Refrigerator Repair'
);
